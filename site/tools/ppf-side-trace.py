def T(p): return (round(100 + (p[0] - 95) * K, 1), round(370 - (540 - p[1]) * K, 1))
def f(v): return f"{v:g}"

def smooth(pts, closed=False, t=0.5):
    """Catmull-Rom through pts (already converted) -> cubic segments (no M)."""
    P = pts[:]
    n = len(P)
    out = []
    rng = range(n if closed else n - 1)
    for i in rng:
        p0 = P[i - 1] if (i > 0 or closed) else P[i]
        p1 = P[i]; p2 = P[(i + 1) % n]
        p3 = P[(i + 2) % n] if (i + 2 < n or closed) else p2
        c1 = (p1[0] + (p2[0] - p0[0]) * t / 3, p1[1] + (p2[1] - p0[1]) * t / 3)
        c2 = (p2[0] - (p3[0] - p1[0]) * t / 3, p2[1] - (p3[1] - p1[1]) * t / 3)
        out.append(f"C{c1[0]:.1f} {c1[1]:.1f} {c2[0]:.1f} {c2[1]:.1f} {p2[0]:g} {p2[1]:g}")
    return " ".join(out)

def path(photo_pts, closed=False):
    P = [T(p) for p in photo_pts]
    return f"M{P[0][0]:g} {P[0][1]:g} " + smooth(P, closed) + (" Z" if closed else "")

def poly(photo_pts):
    P = [T(p) for p in photo_pts]
    return "M" + " L".join(f"{x:g} {y:g}" for x, y in P) + " Z"

